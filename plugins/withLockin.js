// LOCKIN config plugin. Runs during `expo prebuild` (locally or on EAS).
//
// Both variants:
//   - <meta-data android:name="lockin.variant"> read by Kotlin (Variant.kt)
//   - android:dataExtractionRules excluding everything (allowBackup=false is set in app.config.ts)
//     https://developer.android.com/identity/data/autobackup
//   - <queries> for MAIN/LAUNCHER and MAIN/HOME instead of QUERY_ALL_PACKAGES
//     https://developer.android.com/training/package-visibility/declaring
// Hardline only:
//   - DeviceAdminReceiver + res/xml/lockin_device_admin.xml
//   - res/xml/lockin_accessibility_service.xml override (window content access for Settings guard)
//
// Common components (service, activity, receivers, accessibility service) live in
// modules/focus-enforcement/android/src/main/AndroidManifest.xml and are merged by Gradle.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const MODULE_PKG = 'expo.modules.focusenforcement';

const EXCLUDE_ALL = [
  'root',
  'file',
  'database',
  'sharedpref',
  'external',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
]
  .map((d) => `    <exclude domain="${d}" path="." />`)
  .join('\n');

const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withLockin.js. Nothing leaves the device: no cloud backup, no device transfer. -->
<data-extraction-rules>
  <cloud-backup>
${EXCLUDE_ALL}
  </cloud-backup>
  <device-transfer>
${EXCLUDE_ALL}
  </device-transfer>
</data-extraction-rules>
`;

// An empty policy set is enough: an active admin cannot be uninstalled until it is deactivated,
// and Device Owner provisioning only needs a DeviceAdminReceiver component.
// https://developer.android.com/reference/android/app/admin/DeviceAdminReceiver
const DEVICE_ADMIN_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withLockin.js (hardline only). -->
<device-admin>
  <uses-policies />
</device-admin>
`;

// Hardline needs window content to recognise protected Settings screens (App info for our
// package, Accessibility, Device admin, Force stop). Still no gestures, no key filtering.
// https://developer.android.com/reference/android/accessibilityservice/AccessibilityServiceInfo
const HARDLINE_A11Y_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withLockin.js (hardline only). Overrides the module's play-safe config. -->
<accessibility-service xmlns:android="http://schemas.android.com/apk/res/android"
  android:accessibilityEventTypes="typeWindowStateChanged"
  android:accessibilityFeedbackType="feedbackGeneric"
  android:accessibilityFlags="flagDefault"
  android:canRetrieveWindowContent="true"
  android:notificationTimeout="50"
  android:description="@string/lockin_accessibility_description_hardline" />
`;

const HARDLINE_STRINGS_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withLockin.js (hardline only). -->
<resources>
  <string name="lockin_accessibility_description_hardline">LOCKIN HL watches which app is in front during a focus session and covers apps outside your allowlist. During a session it also reads Settings screen titles so it can cover the screens that would switch LOCKIN off. Nothing leaves the device.</string>
</resources>
`;

function addQueries(manifest) {
  const root = manifest.manifest;
  root.queries = root.queries ?? [{}];
  const q = root.queries[0];
  q.intent = q.intent ?? [];
  for (const category of ['android.intent.category.LAUNCHER', 'android.intent.category.HOME']) {
    const exists = q.intent.some(
      (i) =>
        i.action?.[0]?.$['android:name'] === 'android.intent.action.MAIN' &&
        i.category?.some((c) => c.$['android:name'] === category)
    );
    if (!exists) {
      q.intent.push({
        action: [{ $: { 'android:name': 'android.intent.action.MAIN' } }],
        category: [{ $: { 'android:name': category } }],
      });
    }
  }
}

function addDeviceAdminReceiver(app) {
  app.receiver = app.receiver ?? [];
  const name = `${MODULE_PKG}.LockinDeviceAdminReceiver`;
  if (app.receiver.some((r) => r.$['android:name'] === name)) return;
  app.receiver.push({
    $: {
      'android:name': name,
      'android:exported': 'true',
      'android:permission': 'android.permission.BIND_DEVICE_ADMIN',
      'android:label': '@string/app_name',
    },
    'meta-data': [
      { $: { 'android:name': 'android.app.device_admin', 'android:resource': '@xml/lockin_device_admin' } },
    ],
    'intent-filter': [
      { action: [{ $: { 'android:name': 'android.app.action.DEVICE_ADMIN_ENABLED' } }] },
    ],
  });
}

function writeFile(root, rel, contents) {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

const withLockin = (config, { variant }) => {
  if (variant !== 'play' && variant !== 'hardline') {
    throw new Error(`withLockin: variant must be "play" or "hardline", got "${variant}"`);
  }
  const hardline = variant === 'hardline';

  config = withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults;
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
    AndroidConfig.Manifest.addMetaDataItemToMainApplication(app, 'lockin.variant', variant);
    app.$['android:allowBackup'] = 'false';
    app.$['android:dataExtractionRules'] = '@xml/lockin_data_extraction_rules';
    addQueries(manifest);
    if (hardline) addDeviceAdminReceiver(app);
    return cfg;
  });

  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const res = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res');
      writeFile(res, 'xml/lockin_data_extraction_rules.xml', DATA_EXTRACTION_RULES);
      if (hardline) {
        writeFile(res, 'xml/lockin_device_admin.xml', DEVICE_ADMIN_XML);
        writeFile(res, 'xml/lockin_accessibility_service.xml', HARDLINE_A11Y_XML);
        writeFile(res, 'values/lockin_hardline_strings.xml', HARDLINE_STRINGS_XML);
      }
      return cfg;
    },
  ]);

  return config;
};

module.exports = withLockin;
